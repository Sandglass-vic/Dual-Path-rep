#!/usr/bin/env bash
# Allocate P+D engine nodes, with Router/replay colocated on Decode by default.
set -euo pipefail

# Default experiment configuration. Override any value for one invocation with
# NAME=value scripts/pd_alloc.sh P D.
DEFAULT_RUNTIME_HOME=/data/home/yongxiao/mydata
DEFAULT_IMAGE_NAME=images/sglang:26.01-py3-mooncake0.3.13.post1-dualpath-patched-l3bps-20260929-nich2d-async-kvtrans-hostpin.sqsh
DEFAULT_PARTITION=run
DEFAULT_TIME_LIMIT=02:00:00
DEFAULT_ENGINE_CPUS=192
DEFAULT_CLIENT_CPUS=8
DEFAULT_ENGINE_GPUS=4
DEFAULT_TP_SIZE=4
DEFAULT_CLIENT_PLACEMENT=decode
DEFAULT_EXCLUDE=

write_allocation_config() {
  : "${ALLOC_JOB_ID:?ALLOC_JOB_ID is required}"
  : "${RUNTIME_HOME:?RUNTIME_HOME is required}"
  local config_dir config_path name
  config_dir="$RUNTIME_HOME/config/allocations"
  config_path="$config_dir/$ALLOC_JOB_ID.env"
  mkdir -p "$config_dir"
  umask 077
  {
    printf '# Generated by scripts/pd_alloc.sh; static run configuration.\n'
    for name in ALLOC_JOB_ID PREFILL_HOSTS DECODE_HOSTS CLIENT_HOST \
      ROUTER_HOST IMAGE CLIENT_PLACEMENT ENGINE_GPUS TP_SIZE \
      ENGINE_CPUS CLIENT_CPUS RUNTIME_HOME; do
      printf 'export %s=%q\n' "$name" "${!name}"
    done
  } >"$config_path.tmp.$$"
  mv -f "$config_path.tmp.$$" "$config_path"
  chmod 600 "$config_path"
}

run_allocation_config_step() {
  srun --jobid="$ALLOC_JOB_ID" --overlap --nodes=1 --ntasks=1 \
    --nodelist="$CLIENT_HOST" --cpus-per-task=1 --gres=none --mpi=none \
    "$@"
}

cleanup_allocation_config() {
  [[ ${PD_KEEP_ALLOCATION_ENV:-0} == 1 ]] && return 0
  if [[ ${allocation_config_is_local:-0} == 1 ]]; then
    rm -f -- "$allocation_config_path"
  else
    run_allocation_config_step rm -f -- "$allocation_config_path" || true
  fi
}

run_allocation_shell() {
  : "${SLURM_JOB_ID:?This mode must run as the command of salloc}"
  : "${SLURM_JOB_NODELIST:?SLURM_JOB_NODELIST is required}"
  : "${PREFILL_NODES:?PREFILL_NODES is required}"
  : "${DECODE_NODES:?DECODE_NODES is required}"
  CODE_HOME=${CODE_HOME:-/data/home/yongxiao/dual-path}
  RUNTIME_HOME=${RUNTIME_HOME:-$DEFAULT_RUNTIME_HOME}

  local expected client_host host index
  local -a hosts prefill_hosts decode_hosts
  if [[ -n ${DUALPATH_ALLOCATED_HOSTS:-} ]]; then
    read -r -a hosts <<<"$DUALPATH_ALLOCATED_HOSTS"
  else
    mapfile -t hosts < <(scontrol show hostnames "$SLURM_JOB_NODELIST")
  fi
  if [[ $CLIENT_PLACEMENT == decode ]]; then
    expected=$((PREFILL_NODES + DECODE_NODES))
  else
    expected=$((PREFILL_NODES + DECODE_NODES + 1))
  fi
  if (( ${#hosts[@]} != expected )); then
    echo "Expected $expected allocated nodes, got ${#hosts[@]}: ${hosts[*]}" >&2
    return 1
  fi

  prefill_hosts=("${hosts[@]:0:PREFILL_NODES}")
  decode_hosts=("${hosts[@]:PREFILL_NODES:DECODE_NODES}")
  if [[ $CLIENT_PLACEMENT == decode ]]; then
    client_host=${decode_hosts[DECODE_NODES-1]}
  else
    client_host=${hosts[expected-1]}
  fi
  export ALLOC_JOB_ID=$SLURM_JOB_ID
  export PREFILL_HOSTS="${prefill_hosts[*]}"
  export DECODE_HOSTS="${decode_hosts[*]}"
  export CLIENT_HOST=$client_host ROUTER_HOST=$client_host

  allocation_config_path="$RUNTIME_HOME/config/allocations/$ALLOC_JOB_ID.env"
  allocation_config_is_local=0
  if [[ ${PD_FORCE_CONFIG_SRUN:-0} != 1 && -d $RUNTIME_HOME && -w $RUNTIME_HOME ]]; then
    allocation_config_is_local=1
    write_allocation_config
  else
    run_allocation_config_step \
      bash "$CODE_HOME/scripts/pd_alloc.sh" __write_allocation_config
  fi

  trap cleanup_allocation_config EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM

  printf '\nDualPath allocation %s\n' "$ALLOC_JOB_ID"
  printf 'config: %s\n\n' "$allocation_config_path"
  for index in "${!prefill_hosts[@]}"; do
    printf '%-18s prefill-%s\n' "${prefill_hosts[index]}" "$index"
  done
  for index in "${!decode_hosts[@]}"; do
    printf '%-18s decode-%s\n' "${decode_hosts[index]}" "$index"
  done
  if [[ $CLIENT_PLACEMENT == decode ]]; then
    printf '%-18s client (colocated with decode-%s)\n' \
      "$client_host" "$((DECODE_NODES - 1))"
  else
    printf '%-18s client\n' "$client_host"
  fi
  printf '\nOpen one terminal per node, then run the role command after login:\n'
  for index in "${!prefill_hosts[@]}"; do
    printf '\n  # prefill-%s\n  ssh %s\n  cd %s && DUALPATH_L3_READ_PATH=<prefill|decode> scripts/pd_benchmark.sh prefill\n' \
      "$index" "${prefill_hosts[index]}" "$CODE_HOME"
  done
  for index in "${!decode_hosts[@]}"; do
    printf '\n  # decode-%s\n  ssh %s\n  cd %s && DUALPATH_L3_READ_PATH=<prefill|decode> scripts/pd_benchmark.sh decode\n' \
      "$index" "${decode_hosts[index]}" "$CODE_HOME"
  done
  printf '\n  # client\n  ssh %s\n' "$client_host"
  printf '  cd %s && DATASET=32K AGENTS=1 REPETITION=1 DUALPATH_L3_READ_PATH=<prefill|decode> scripts/pd_benchmark.sh client\n' \
    "$CODE_HOME"
  printf '\nKeep this shell open until every node-local srun has stopped.\n'
  printf '\nShared run root: %q\n' "$RUNTIME_HOME/test/$ALLOC_JOB_ID"
  printf '  task logs/results: %q/<TASK_NAME>/logs\n' "$RUNTIME_HOME/test/$ALLOC_JOB_ID"
  printf '\nCold-cache cleanup for this allocation (run only after stopping Prefill/Decode and releasing the allocation):\n'
  printf '  rm -rf %q\n\n' "$RUNTIME_HOME/test/$ALLOC_JOB_ID/pd-servers/kv-cache"

  if [[ ${PD_ALLOCATION_NO_SHELL:-0} == 1 ]]; then
    return 0
  fi
  PS1="[dualpath alloc $ALLOC_JOB_ID] \u@\h:\w\$ " bash -i
}

if [[ ${1:-} == __write_allocation_config ]]; then
  write_allocation_config
  exit $?
fi

if [[ ${1:-} == __allocation_shell ]]; then
  run_allocation_shell
  exit $?
fi

usage() {
  cat <<'EOF'
Usage: scripts/pd_alloc.sh [PREFILL_NODES] [DECODE_NODES]

Defaults: 1P1D TP4, Decode-colocated client, Prefill L3 read, pza100 image.
Workload settings belong to the client command, for example:
  DATASET=64K AGENTS=8 REPETITION=2 scripts/pd_benchmark.sh client

Allocation stores topology/resources/image/TP size only. Runtime settings such
as DUALPATH_L3_READ_PATH, DUAL_PATH_O_DIRECT_READ, ABLATION_PROFILE, context
length, and HiCache parameters belong to each pd_benchmark.sh command.

Common allocation overrides:
  IMAGE CLIENT_PLACEMENT ENGINE_GPUS TP_SIZE
  PARTITION TIME_LIMIT EXCLUDE ENGINE_CPUS CLIENT_CPUS ALLOC_NAME
EOF
}

if [[ ${1:-} == -h || ${1:-} == --help ]]; then
  usage
  exit 0
fi
if (( $# > 2 )); then
  usage >&2
  exit 2
fi

PREFILL_NODES=${1:-${PREFILL_NODES:-1}}
DECODE_NODES=${2:-${DECODE_NODES:-1}}
for name in PREFILL_NODES DECODE_NODES; do
  [[ ${!name} =~ ^[1-9][0-9]*$ ]] || {
    echo "$name must be a positive integer" >&2
    exit 2
  }
done

CODE_HOME=${CODE_HOME:-/data/home/yongxiao/dual-path}
RUNTIME_HOME=${RUNTIME_HOME:-$DEFAULT_RUNTIME_HOME}
IMAGE=${IMAGE:-$RUNTIME_HOME/$DEFAULT_IMAGE_NAME}
PARTITION=${PARTITION:-$DEFAULT_PARTITION}
TIME_LIMIT=${TIME_LIMIT:-$DEFAULT_TIME_LIMIT}
ENGINE_CPUS=${ENGINE_CPUS:-$DEFAULT_ENGINE_CPUS}
CLIENT_CPUS=${CLIENT_CPUS:-$DEFAULT_CLIENT_CPUS}
ENGINE_GPUS=${ENGINE_GPUS:-$DEFAULT_ENGINE_GPUS}
TP_SIZE=${TP_SIZE:-$DEFAULT_TP_SIZE}
CLIENT_PLACEMENT=${CLIENT_PLACEMENT:-$DEFAULT_CLIENT_PLACEMENT}
EXCLUDE=${EXCLUDE:-$DEFAULT_EXCLUDE}
ALLOC_NAME=${ALLOC_NAME:-${PREFILL_NODES}p${DECODE_NODES}d-alloc-$(date +%Y%m%d-%H%M%S)}

for name in ENGINE_CPUS CLIENT_CPUS ENGINE_GPUS TP_SIZE; do
  [[ ${!name} =~ ^[1-9][0-9]*$ ]] || {
    echo "$name must be a positive integer" >&2
    exit 2
  }
done
if (( TP_SIZE > ENGINE_GPUS )); then
  echo "TP_SIZE ($TP_SIZE) cannot exceed ENGINE_GPUS ($ENGINE_GPUS)" >&2
  exit 2
fi
[[ $CLIENT_PLACEMENT == decode || $CLIENT_PLACEMENT == separate ]] || {
  echo "CLIENT_PLACEMENT must be decode or separate" >&2
  exit 2
}
if [[ $CLIENT_PLACEMENT == decode ]]; then
  nodes=$((PREFILL_NODES + DECODE_NODES))
else
  nodes=$((PREFILL_NODES + DECODE_NODES + 1))
fi
export CODE_HOME RUNTIME_HOME PREFILL_NODES DECODE_NODES
export IMAGE CLIENT_PLACEMENT ENGINE_GPUS TP_SIZE
export ENGINE_CPUS CLIENT_CPUS

command=(
  salloc --partition="$PARTITION" --nodes="$nodes" --ntasks="$nodes"
  --ntasks-per-node=1 --cpus-per-task="$ENGINE_CPUS" --gres="gpu:$ENGINE_GPUS"
  --mem=0
  --exclusive --time="$TIME_LIMIT" --job-name="dualpath-$ALLOC_NAME"
)
if [[ -n $EXCLUDE ]]; then
  command+=(--exclude="$EXCLUDE")
fi
command+=(bash "$CODE_HOME/scripts/pd_alloc.sh" __allocation_shell)

printf 'Requesting %sP%sD, client=%s: %s nodes, TP=%s, GPUs/engine=%s, allocation=%s\n' \
  "$PREFILL_NODES" "$DECODE_NODES" "$CLIENT_PLACEMENT" "$nodes" \
  "$TP_SIZE" "$ENGINE_GPUS" "$ALLOC_NAME"
if [[ ${PD_DRY_RUN:-0} == 1 ]]; then
  printf '%q ' "${command[@]}"
  printf '\n'
  exit 0
fi
exec "${command[@]}"
